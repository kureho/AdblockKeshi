import Foundation
import KurehoKit

/// 買うと何が変わるかの**唯一の定義**。購入画面はここから作る。
///
/// ★書き方は**対比**（2026-09-18 に 3 案を実機で比べて kureho が案 B を採用・22 本共通）。
///   ❌ 便益の文を 4 行並べる（「他アプリ・Safari の広告を端末内で抑える」など）
///   → ✅ **同じ行の左右に「無料だとこう / 購入後はこう」を置く**
///   → 理由: 旧画面の 4 行は**どれも「買うと得られるもの」の言い換え**で、
///     無料のままで何ができるかが書かれていなかった。このアプリで一番多い誤解
///     （「Safari の広告ブロックを買うのだと思った」）がそこから出る。
///
/// ★**このアプリだけ KurehoKit を使っていなかった**（2026-09-18 に依存を追加して 22 本そろえた）。
enum ProCatalog {

    /// ★行は**差があるものだけ**。実際にコードで止めているのは `DNSSettingsView` の 1 か所＝1 行。
    ///   ❌ 「Safari の広告: 出ない / 出ない」を足して表を厚く見せる
    ///   → ✅ 無料でもう消えているものは `freeSummary` で言う
    ///   → 理由: 左右が同じ行は対比になっておらず、共通部品の検査（`PaywallCopyAudit`）が弾く。
    ///     この棚で一番多い誤解「Safari の広告ブロックを買うのだと思った」は、
    ///     表の行ではなく**見出しのすぐ下の無料の範囲**で先に断つ。
    static let rows: [PaywallFeature] = [
        .init(symbol: "apps.iphone", title: "他アプリの広告", free: "出る", plus: "抑える"),
    ]

    /// ★**1 行に収まる長さにする**（2026-09-18）。20 字あると iPhone の幅で折り返し、
    ///   「Safari の広告消し / は、ずっと無料です。」と助詞の途中で割れて読みにくかった。
    ///   何が無料かは下の `freeSummary` が受け持つので、見出しは短くてよい。
    static let headline = "広告消しは、ずっと無料です。"

    static let freeSummary = "Safari の広告ブロック・フィルタの自動更新・壊れ報告は、無料のまま使えます。"

    /// 購入ボタンの下の 1 段落。
    /// ★**おさえられない先をここに畳んだ**（旧 `limitsNote` の別ブロックを廃止）。
    ///   訴求規律「限界を明記する」は変えずに、読む場所を 1 つに減らす。
    static let paymentNote = "お支払いは 1 回だけです。月額・年額の課金はありません。"
        + "YouTube・X・Instagram・一部ゲームの広告は、仕組み上おさえられません。"

    /// 有料側の列の見出し。このアプリに「Plus」という商品名は無い。
    static let paidLabel = "購入後"
}
